"""
FoodieAnalytics - Data Loader Module
Handles cached, memory-efficient data retrieval from precomputed
Spark SQL analytical results, clustered Parquet data, and streaming reports.
"""

import os
import glob
import pandas as pd
import streamlit as st

# Locate project base directory dynamically
def get_base_dir() -> str:
    """Return the absolute base directory of the BDA-miniproject workspace."""
    # Current file is in app/utils/data_loader.py -> base is ../../
    current_dir = os.path.dirname(os.path.abspath(__file__))
    base_dir = os.path.abspath(os.path.join(current_dir, "..", ".."))
    return base_dir


def find_csv_file(directory_path: str) -> str:
    """
    Find the primary CSV data file inside a Spark output directory,
    filtering out hidden files (._*), checksum files (.crc), and _SUCCESS markers.
    """
    if not os.path.exists(directory_path):
        raise FileNotFoundError(f"Directory not found: {directory_path}")
    
    candidates = glob.glob(os.path.join(directory_path, "*.csv"))
    valid_files = [
        f for f in candidates
        if not os.path.basename(f).startswith(".") and not os.path.basename(f).startswith("_")
    ]
    if not valid_files:
        raise FileNotFoundError(f"No valid CSV data file found in {directory_path}")
    return sorted(valid_files)[0]


@st.cache_data(show_spinner=False)
def load_css() -> str:
    """Load the custom CSS styles file and return its content."""
    base_dir = get_base_dir()
    css_path = os.path.join(base_dir, "app", "assets", "styles.css")
    if os.path.exists(css_path):
        with open(css_path, "r", encoding="utf-8") as f:
            return f.read()
    return ""


def apply_custom_css():
    """Inject custom CSS into the Streamlit app."""
    css = load_css()
    if css:
        st.markdown(f"<style>{css}</style>", unsafe_allow_html=True)


QUERY_DIR_MAPPING = {
    1: "query01_restaurants_by_location",
    2: "query02_popular_cuisines",
    3: "query03_average_rating_by_location",
    4: "query04_top_rated_restaurants",
    5: "query05_average_cost_by_location",
    6: "query06_online_delivery_analysis",
    7: "query07_price_range_distribution",
    8: "query08_rating_votes_relationship"
}


@st.cache_data(ttl=3600, show_spinner=False)
def load_spark_query(query_id: int) -> pd.DataFrame:
    """
    Load a precomputed Spark SQL query result CSV by query ID (1 to 8).
    Cached for high performance.
    """
    base_dir = get_base_dir()
    query_folder = QUERY_DIR_MAPPING.get(query_id)
    if not query_folder:
        raise ValueError(f"Invalid query ID {query_id}. Valid IDs are 1 to 8.")
    
    full_path = os.path.join(base_dir, "reports", "spark_results", query_folder)
    csv_file = find_csv_file(full_path)
    df = pd.read_csv(csv_file)
    return df


@st.cache_data(ttl=3600, show_spinner=False)
def load_all_spark_queries() -> dict[int, pd.DataFrame]:
    """Load all 8 Spark SQL queries into a dictionary."""
    results = {}
    for q_id in range(1, 9):
        try:
            results[q_id] = load_spark_query(q_id)
        except Exception as e:
            st.error(f"Error loading Query {q_id}: {e}")
            results[q_id] = pd.DataFrame()
    return results


@st.cache_data(ttl=3600, show_spinner=False)
def load_clustered_restaurants() -> pd.DataFrame:
    """
    Load the clustered restaurant dataset (Stage 8 MLlib output) from Parquet.
    Extracts essential columns for filtering, sorting, and recommendation.
    """
    base_dir = get_base_dir()
    parquet_path = os.path.join(base_dir, "dataset", "processed", "clustered_restaurants")
    
    # We select explicit scalar columns to avoid deserializing complex VectorUDT features
    columns_to_load = [
        "name",
        "location_clean",
        "cuisines",
        "primary_cuisine",
        "rating_num",
        "votes_num",
        "cost_for_two_num",
        "online_order_bool",
        "book_table_bool",
        "cluster_id"
    ]
    
    if not os.path.exists(parquet_path):
        raise FileNotFoundError(f"Clustered restaurants Parquet not found at: {parquet_path}")
    
    df = pd.read_parquet(parquet_path, columns=columns_to_load)
    
    # Fill or clean any missing values for reliable UI presentation
    df["rating_num"] = pd.to_numeric(df["rating_num"], errors="coerce")
    df["cost_for_two_num"] = pd.to_numeric(df["cost_for_two_num"], errors="coerce")
    df["votes_num"] = pd.to_numeric(df["votes_num"], errors="coerce").fillna(0).astype(int)
    df["location_clean"] = df["location_clean"].fillna("Unknown")
    df["cuisines"] = df["cuisines"].fillna("Unknown")
    
    return df


@st.cache_data(ttl=3600, show_spinner=False)
def load_streaming_summaries() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Load the 3 streaming analytical summaries generated by Spark Structured Streaming in Stage 9:
    - overall_summary
    - restaurant_summary
    - status_summary
    """
    base_dir = get_base_dir()
    stream_base = os.path.join(base_dir, "reports", "streaming")
    
    overall_path = find_csv_file(os.path.join(stream_base, "overall_summary"))
    restaurant_path = find_csv_file(os.path.join(stream_base, "restaurant_summary"))
    status_path = find_csv_file(os.path.join(stream_base, "status_summary"))
    
    df_overall = pd.read_csv(overall_path)
    df_restaurant = pd.read_csv(restaurant_path)
    df_status = pd.read_csv(status_path)
    
    return df_overall, df_restaurant, df_status


@st.cache_data(ttl=3600, show_spinner=False)
def load_streaming_orders() -> pd.DataFrame:
    """
    Load the 50 consolidated simulated orders processed across 10 micro-batches
    in Stage 9 from Snappy Parquet.
    """
    base_dir = get_base_dir()
    processed_orders_path = os.path.join(base_dir, "reports", "streaming", "processed_orders")
    
    if not os.path.exists(processed_orders_path):
        raise FileNotFoundError(f"Processed orders not found at {processed_orders_path}")
    
    df_orders = pd.read_parquet(processed_orders_path)
    if "order_amount" in df_orders.columns:
        df_orders["order_amount"] = pd.to_numeric(df_orders["order_amount"], errors="coerce")
    return df_orders


@st.cache_data(show_spinner=False)
def get_dataset_kpis() -> dict:
    """
    Compute or retrieve overall macro KPIs across the entire 51,656 restaurant dataset
    using precomputed Spark query aggregates for instant rendering.
    """
    df_loc = load_spark_query(1)      # 93 locations, 51,656 restaurants
    df_cost = load_spark_query(5)     # Average cost per locality
    df_rating = load_spark_query(3)   # Average rating per locality
    df_delivery = load_spark_query(6) # Online delivery rates
    df_corr = load_spark_query(8)     # Correlation 0.434 on 41,640 records
    
    total_restaurants = int(df_loc["total_restaurants"].sum()) if not df_loc.empty else 51656
    total_localities = len(df_loc) if not df_loc.empty else 93
    
    # Weighted average rating across rated restaurants
    if not df_rating.empty and "average_rating" in df_rating.columns:
        weighted_rating = (
            (df_rating["average_rating"] * df_rating["rated_restaurant_count"]).sum() /
            df_rating["rated_restaurant_count"].sum()
        )
    else:
        weighted_rating = 3.70
        
    # Weighted average cost for two across valid cost records
    if not df_cost.empty and "average_cost_for_two" in df_cost.columns:
        weighted_cost = (
            (df_cost["average_cost_for_two"] * df_cost["valid_cost_records"]).sum() /
            df_cost["valid_cost_records"].sum()
        )
    else:
        weighted_cost = 555.33

    # Overall online delivery adoption
    if not df_delivery.empty and "online_order_restaurants" in df_delivery.columns:
        online_pct = (
            df_delivery["online_order_restaurants"].sum() /
            df_delivery["total_restaurants"].sum()
        ) * 100
    else:
        online_pct = 58.85
        
    correlation = float(df_corr["rating_votes_correlation"].iloc[0]) if not df_corr.empty else 0.434
    
    return {
        "total_restaurants": total_restaurants,
        "total_localities": total_localities,
        "average_rating": round(weighted_rating, 2),
        "average_cost_for_two": round(weighted_cost, 2),
        "online_delivery_pct": round(online_pct, 1),
        "rating_votes_correlation": correlation
    }

