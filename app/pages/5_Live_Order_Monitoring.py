"""
FoodieAnalytics - Live Order Monitoring Dashboard (Stage 9 Outputs)
Stage 10 - Interactive Dashboard and Final Application

Visualizes the 50 simulated food delivery orders processed across 10 JSON 
micro-batches using Spark Structured Streaming in Stage 9.
"""

import streamlit as st
import plotly.express as px
import plotly.graph_objects as go
import pandas as pd

from utils.data_loader import (
    apply_custom_css,
    load_streaming_summaries,
    load_streaming_orders
)

st.set_page_config(
    page_title="Live Order Monitoring | FoodieAnalytics",
    page_icon="⚡",
    layout="wide"
)

apply_custom_css()

# Header
st.markdown("""
    <div class="header-banner">
        <h1>⚡ Simulated Live Order Monitoring (Stage 9)</h1>
        <p>
            Near real-time analytics of 50 simulated food delivery orders processed across 
            10 JSON micro-batches using Apache Spark Structured Streaming with file-based ingestion,
            Parquet persistence, and checkpoint fault tolerance.
        </p>
        <div class="tech-badges">
            <span class="tech-badge">🌊 Spark Structured Streaming</span>
            <span class="tech-badge">📦 10 JSON Micro-Batches</span>
            <span class="tech-badge">📊 50 Simulated Orders</span>
            <span class="tech-badge">🏪 10 Partner Restaurants</span>
            <span class="tech-badge">💾 Snappy Parquet Storage</span>
        </div>
    </div>
""", unsafe_allow_html=True)

st.info("""
**ℹ️ About This Dashboard**  
These analytics were generated by executing the Stage 9 Spark Structured Streaming pipeline in Ubuntu WSL2.  
The order generator (`order_generator.py`) produced **50 synthetic orders** across **10 micro-batch JSON files** with realistic order amounts (₹150–₹2,000), random restaurant assignments across 10 simulated partners (REST001–REST010), and varied order statuses (Placed, Preparing, Out for Delivery, Delivered).  
This is **not a live feed** — it represents the final consolidated snapshot from the completed batch run.
""")

# Load all streaming data
df_overall, df_restaurants, df_status = load_streaming_summaries()
df_orders = load_streaming_orders()

# Top KPI Cards
col1, col2, col3, col4, col5 = st.columns(5)

total_orders = int(df_overall["total_orders"].iloc[0]) if not df_overall.empty else 50
total_revenue = float(df_overall["total_revenue"].iloc[0]) if not df_overall.empty else 50282.49
avg_order_val = float(df_overall["average_order_value"].iloc[0]) if not df_overall.empty else 1005.65

with col1:
    st.markdown(f"""
        <div class="kpi-card">
            <div class="kpi-title">Total Orders Processed</div>
            <div class="kpi-value">{total_orders}</div>
            <div class="kpi-subtitle">📦 Across 10 micro-batches</div>
        </div>
    """, unsafe_allow_html=True)

with col2:
    st.markdown(f"""
        <div class="kpi-card">
            <div class="kpi-title">Gross Merchandise Value</div>
            <div class="kpi-value">₹{total_revenue:,.2f}</div>
            <div class="kpi-subtitle">💰 Total simulated GMV</div>
        </div>
    """, unsafe_allow_html=True)

with col3:
    st.markdown(f"""
        <div class="kpi-card">
            <div class="kpi-title">Avg Order Value (AOV)</div>
            <div class="kpi-value">₹{avg_order_val:,.2f}</div>
            <div class="kpi-subtitle">📈 Per completed order</div>
        </div>
    """, unsafe_allow_html=True)

with col4:
    if not df_restaurants.empty:
        top_rest = df_restaurants.iloc[0]["restaurant_id"]
        top_rest_rev = float(df_restaurants.iloc[0]["total_revenue"])
    else:
        top_rest, top_rest_rev = "REST004", 10871.0
    st.markdown(f"""
        <div class="kpi-card">
            <div class="kpi-title">Top Revenue Partner</div>
            <div class="kpi-value">{top_rest}</div>
            <div class="kpi-subtitle">🏆 ₹{top_rest_rev:,.0f} generated</div>
        </div>
    """, unsafe_allow_html=True)

with col5:
    if not df_status.empty:
        delivered_row = df_status[df_status["order_status"] == "Delivered"]
        delivered_cnt = int(delivered_row["total_orders"].iloc[0]) if not delivered_row.empty else 17
    else:
        delivered_cnt = 17
    st.markdown(f"""
        <div class="kpi-card">
            <div class="kpi-title">Orders Delivered</div>
            <div class="kpi-value">{delivered_cnt}</div>
            <div class="kpi-subtitle">✅ {(delivered_cnt / total_orders * 100):.0f}% completion rate</div>
        </div>
    """, unsafe_allow_html=True)

st.markdown("<br>", unsafe_allow_html=True)

# Section 1: Restaurant Performance Charts
col_rest_orders, col_rest_rev = st.columns(2)

with col_rest_orders:
    st.markdown("""
        <div class="section-card">
            <div class="section-title">🍽️ Orders Processed per Restaurant</div>
            <div class="section-subtitle">Total micro-batch orders assigned to each of 10 restaurant partners</div>
        </div>
    """, unsafe_allow_html=True)

    if not df_restaurants.empty:
        df_r_sorted = df_restaurants.sort_values("total_orders", ascending=True)
        fig_orders_rest = px.bar(
            df_r_sorted,
            x="total_orders",
            y="restaurant_id",
            orientation="h",
            color="total_orders",
            color_continuous_scale="Reds",
            text="total_orders",
            labels={"total_orders": "Orders Received", "restaurant_id": "Restaurant ID"}
        )
        fig_orders_rest.update_layout(
            margin=dict(l=20, r=20, t=10, b=20),
            coloraxis_showscale=False,
            height=360,
            font=dict(family="Inter, sans-serif")
        )
        fig_orders_rest.update_traces(textposition="outside", cliponaxis=False)
        st.plotly_chart(fig_orders_rest, use_container_width=True)

with col_rest_rev:
    st.markdown("""
        <div class="section-card">
            <div class="section-title">💰 Revenue Generated per Restaurant</div>
            <div class="section-subtitle">Total simulated GMV contribution from each partner restaurant</div>
        </div>
    """, unsafe_allow_html=True)

    if not df_restaurants.empty:
        df_rev_sorted = df_restaurants.sort_values("total_revenue", ascending=True)
        fig_rev = px.bar(
            df_rev_sorted,
            x="total_revenue",
            y="restaurant_id",
            orientation="h",
            color="total_revenue",
            color_continuous_scale="Teal",
            text="total_revenue",
            labels={"total_revenue": "Total Revenue (₹)", "restaurant_id": "Restaurant ID"}
        )
        fig_rev.update_layout(
            margin=dict(l=20, r=20, t=10, b=20),
            coloraxis_showscale=False,
            height=360,
            font=dict(family="Inter, sans-serif")
        )
        fig_rev.update_traces(texttemplate='₹%{x:,.0f}', textposition="outside", cliponaxis=False)
        st.plotly_chart(fig_rev, use_container_width=True)

# Section 2: Order Status Distribution + AOV by Restaurant
col_status, col_aov = st.columns(2)

with col_status:
    st.markdown("""
        <div class="section-card">
            <div class="section-title">📋 Order Fulfillment Status Distribution</div>
            <div class="section-subtitle">Random statuses assigned from: Placed, Preparing, Out for Delivery, Delivered</div>
        </div>
    """, unsafe_allow_html=True)

    if not df_status.empty:
        status_colors = {
            "Delivered": "#10B981",
            "Out for Delivery": "#3B82F6",
            "Preparing": "#F59E0B",
            "Placed": "#8B5CF6"
        }
        fig_status = px.pie(
            df_status,
            names="order_status",
            values="total_orders",
            color="order_status",
            color_discrete_map=status_colors,
            hole=0.42
        )
        fig_status.update_layout(
            margin=dict(l=20, r=20, t=10, b=20),
            height=350,
            font=dict(family="Inter, sans-serif")
        )
        st.plotly_chart(fig_status, use_container_width=True)

        # Status breakdown table
        st.dataframe(
            df_status.rename(columns={
                "order_status": "Status",
                "total_orders": "Orders",
                "total_order_value": "Total Value (₹)"
            }).sort_values("Orders", ascending=False),
            use_container_width=True,
            hide_index=True
        )

with col_aov:
    st.markdown("""
        <div class="section-card">
            <div class="section-title">📊 Average Order Value by Restaurant</div>
            <div class="section-subtitle">Revenue efficiency per order per partner (AOV metric)</div>
        </div>
    """, unsafe_allow_html=True)

    if not df_restaurants.empty:
        fig_aov = px.bar(
            df_restaurants.sort_values("average_order_value", ascending=True),
            x="average_order_value",
            y="restaurant_id",
            orientation="h",
            color="average_order_value",
            color_continuous_scale="Peach",
            text="average_order_value",
            labels={"average_order_value": "Avg Order Value (₹)", "restaurant_id": "Restaurant ID"}
        )
        fig_aov.update_layout(
            margin=dict(l=20, r=20, t=10, b=20),
            coloraxis_showscale=False,
            height=360,
            font=dict(family="Inter, sans-serif")
        )
        fig_aov.update_traces(texttemplate='₹%{x:,.0f}', textposition="outside", cliponaxis=False)
        st.plotly_chart(fig_aov, use_container_width=True)

# Section 3: Order Timeline (Order Amount over time)
st.markdown("<br>", unsafe_allow_html=True)
if not df_orders.empty:
    st.markdown("""
        <div class="section-card">
            <div class="section-title">📈 Order Amount Timeline</div>
            <div class="section-subtitle">Individual order amounts across the 50 simulated orders (sorted by order ID)</div>
        </div>
    """, unsafe_allow_html=True)

    df_timeline = df_orders.copy()
    df_timeline["order_num"] = range(1, len(df_timeline) + 1)

    fig_timeline = px.scatter(
        df_timeline,
        x="order_num",
        y="order_amount",
        color="order_status",
        hover_data=["order_id", "restaurant_id", "customer_id"],
        color_discrete_map={
            "Delivered": "#10B981",
            "Out for Delivery": "#3B82F6",
            "Preparing": "#F59E0B",
            "Placed": "#8B5CF6"
        },
        labels={"order_num": "Order Sequence", "order_amount": "Order Amount (₹)"},
        title=""
    )
    fig_timeline.add_hline(
        y=avg_order_val,
        line_dash="dash",
        line_color="#E23744",
        annotation_text=f"AOV: ₹{avg_order_val:,.2f}",
        annotation_position="top right"
    )
    fig_timeline.update_layout(
        margin=dict(l=20, r=20, t=20, b=20),
        height=360,
        font=dict(family="Inter, sans-serif")
    )
    st.plotly_chart(fig_timeline, use_container_width=True)

# Section 4: Interactive Order Search Table
st.markdown("<br>", unsafe_allow_html=True)
st.markdown("""
    <div class="section-card">
        <div class="section-title">🔍 Interactive Order Log Explorer</div>
        <div class="section-subtitle">Search and filter all 50 processed streaming orders</div>
    </div>
""", unsafe_allow_html=True)

# Search & filter controls
sc1, sc2, sc3 = st.columns([2, 2, 1])
with sc1:
    search_order = st.text_input("Search by Order ID or Customer ID", placeholder="e.g. ORD1001, CUST42...")
with sc2:
    if not df_orders.empty:
        all_restaurants = ["All Restaurants"] + sorted(df_orders["restaurant_id"].unique().tolist())
        filter_rest = st.selectbox("Filter by Restaurant", all_restaurants)
    else:
        filter_rest = "All Restaurants"
with sc3:
    if not df_orders.empty and "order_status" in df_orders.columns:
        all_statuses = ["All Statuses"] + sorted(df_orders["order_status"].unique().tolist())
        filter_status = st.selectbox("Filter by Status", all_statuses)
    else:
        filter_status = "All Statuses"

# Apply search / filter logic
display_orders = df_orders.copy()
if search_order:
    display_orders = display_orders[
        display_orders["order_id"].str.contains(search_order, case=False, na=False) |
        display_orders["customer_id"].str.contains(search_order, case=False, na=False)
    ]
if filter_rest != "All Restaurants":
    display_orders = display_orders[display_orders["restaurant_id"] == filter_rest]
if filter_status != "All Statuses":
    display_orders = display_orders[display_orders["order_status"] == filter_status]

st.markdown(f"**Showing {len(display_orders)} orders**")
st.dataframe(
    display_orders.rename(columns={
        "order_id": "Order ID",
        "restaurant_id": "Restaurant",
        "customer_id": "Customer",
        "order_amount": "Amount (₹)",
        "order_status": "Status",
        "order_timestamp": "Timestamp"
    }).sort_values("Order ID"),
    use_container_width=True,
    hide_index=True
)

